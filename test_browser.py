from playwright.sync_api import Page


def test_open_site(page: Page):
    page.goto("https://www.saucedemo.com/")
    page.wait_for_timeout(1500)
    username_field = page.locator("id=user-name")
    username_field.type("standard_user")
    password_field = page.locator("id=password")
    password_field.type("secret_sauce")
    page.locator("id=login-button").click()
    page.wait_for_timeout(1500)
    page.wait_for_selector("text=Products")
    assert page.locator("text=Products").is_visible()
    page.locator("text=Sauce Labs Backpack").click()
    page.wait_for_timeout(1500)
    assert page.locator("text=Sauce Labs Backpack").is_visible()
    assert page.locator("text=29.99").is_visible()

    page.locator("text=Add to cart").click()
    page.wait_for_timeout(1500)
    assert page.locator("text=Remove").is_visible()
    page.locator(".shopping_cart_link").click()
    page.wait_for_timeout(1500)
    assert page.locator("text=Sauce Labs Backpack").is_visible()
    page.locator("text=Checkout").click()
    page.wait_for_timeout(1500)
    page.locator("id=first-name").fill("Ivan")
    page.locator("id=last-name").fill("Ivanov")
    page.locator("id=postal-code").fill("1234")
    page.locator("text=Continue").click()
    page.wait_for_timeout(1500)
    assert page.locator("text=Sauce Labs Backpack").is_visible()
    page.locator("text=Finish").click()
    page.wait_for_timeout(1500)
    assert page.locator("text=Thank you for your order!").is_visible()
